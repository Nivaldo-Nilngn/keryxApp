  /// Busca o ID do livro por nome, abreviatura ou ID numérico.
  static int findBookId(String query) {
    if (query.isEmpty) return 1;
    
    // 1. Tenta numérico
    final id = int.tryParse(query);
    if (id != null && id >= 1 && id <= 66) return id;
    
    final lowerQuery = query.toLowerCase().trim();
    
    // 2. Tenta abreviação exata
    for (var entry in bookDetails.entries) {
      if (entry.value['abbrev'].toString().toLowerCase() == lowerQuery) {
        return entry.key;
      }
    }
    
    // 3. Tenta nome completo exato
    for (var entry in bookNames.entries) {
      if (entry.value.toLowerCase() == lowerQuery) {
        return entry.key;
      }
    }
    
    // 4. Busca parcial (mais lento)
    for (var entry in bookNames.entries) {
      final name = entry.value.toLowerCase();
      if (name.contains(lowerQuery) || lowerQuery.contains(name)) {
        return entry.key;
      }
    }

    return 1; // Default Genesis
  }

