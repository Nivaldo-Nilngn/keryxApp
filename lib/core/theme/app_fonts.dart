  static TextStyle getFont(
    String fontName, {
    TextStyle? textStyle,
    Color? color,
    Color? backgroundColor,
    double? fontSize,
    FontWeight? fontWeight,
    FontStyle? fontStyle,
    double? letterSpacing,
    double? wordSpacing,
    TextBaseline? textBaseline,
    double? height,
    Locale? locale,
    Paint? foreground,
    Paint? background,
    List<ui.Shadow>? shadows,
    List<ui.FontFeature>? fontFeatures,
    TextDecoration? decoration,
    Color? decorationColor,
    TextDecorationStyle? decorationStyle,
    double? decorationThickness,
  }) {
    final active = _globalFontFamilyOverride ?? fontName;
    if (CustomFontLoader.loadedFontFamilies.contains(active)) {
      TextStyle s = textStyle ?? const TextStyle();
      return s.copyWith(
        fontFamily: active,
        color: color,
        backgroundColor: backgroundColor,
        fontSize: fontSize,
        fontWeight: fontWeight,
        fontStyle: fontStyle,
        letterSpacing: letterSpacing,
        wordSpacing: wordSpacing,
        textBaseline: textBaseline,
        height: height,
        locale: locale,
        foreground: foreground,
        background: background,
        shadows: shadows,
        fontFeatures: fontFeatures,
        decoration: decoration,
        decorationColor: decorationColor,
        decorationStyle: decorationStyle,
        decorationThickness: decorationThickness,
      );
    }
    return gf.GoogleFonts.getFont(
      active,
      textStyle: textStyle,
      color: color,
      backgroundColor: backgroundColor,
      fontSize: fontSize,
      fontWeight: fontWeight,
      fontStyle: fontStyle,
      letterSpacing: letterSpacing,
      wordSpacing: wordSpacing,
      textBaseline: textBaseline,
      height: height,
      locale: locale,
      foreground: foreground,
      background: background,
      shadows: shadows,
      fontFeatures: fontFeatures,
      decoration: decoration,
      decorationColor: decorationColor,
      decorationStyle: decorationStyle,
      decorationThickness: decorationThickness,
    );
  }

  static TextTheme getTextTheme(String fontName, [TextTheme? textTheme]) {
    final active = _globalFontFamilyOverride ?? fontName;
    if (CustomFontLoader.loadedFontFamilies.contains(active)) {
      final base = textTheme ?? ThemeData.light().textTheme;
      return base.apply(fontFamily: active);
    }
    try {
      return gf.GoogleFonts.getTextTheme(active, textTheme);
    } catch (_) {
      final base = textTheme ?? ThemeData.light().textTheme;
      return base.apply(fontFamily: active);
    }
  }

  static TextTheme outfitTextTheme([TextTheme? textTheme]) {
    final active = _globalFontFamilyOverride ?? 'Outfit';
    return getTextTheme(active, textTheme);
  }

  static TextTheme manropeTextTheme([TextTheme? textTheme]) {
    final active = _globalFontFamilyOverride ?? 'Manrope';
    return getTextTheme(active, textTheme);
  }
