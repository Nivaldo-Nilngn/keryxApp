/// Gerenciador dinâmico de tipografia do KeryxApp.
/// Permite que a fonte e tamanho escolhidos pelo usuário nas Configurações do Sistema
/// sejam aplicados em TODO o aplicativo de maneira transparente e unificada.
class GoogleFonts {
  static String? _globalFontFamilyOverride;

  /// Define a família de fontes global escolhida pelo usuário.
  /// Se null ou 'Outfit', mantém a fonte original do design onde aplicável.
  static void setGlobalFontFamilyOverride(String? font) {
    if (font == null || font.trim().isEmpty) {
      _globalFontFamilyOverride = null;
    } else {
      _globalFontFamilyOverride = font.trim();
    }
  }

  static String? get globalFontFamilyOverride => _globalFontFamilyOverride;

  static gf.Config get config => gf.GoogleFonts.config;

  /// Resolve o TextStyle usando a fonte global ativa ou a fonte de fallback original
  static TextStyle _resolveStyle({
    required String defaultFamily,
    required TextStyle Function() fallback,
    TextStyle? textStyle,
    Color? color,
    Color? backgroundColor,
    double? fontSize,
    FontWeight? fontWeight,
    FontStyle? fontStyle,
    double? letterSpacing,
    double? wordSpacing,
    TextBaseline? textBaseline,
    double? height,
    Locale? locale,
    Paint? foreground,
    Paint? background,
    List<ui.Shadow>? shadows,
    List<ui.FontFeature>? fontFeatures,
    TextDecoration? decoration,
    Color? decorationColor,
    TextDecorationStyle? decorationStyle,
    double? decorationThickness,
  }) {
    final activeFamily = _globalFontFamilyOverride;

    // Se nenhuma fonte global customizada estiver ativa ou for a mesma da original, usa o fallback
    if (activeFamily == null || activeFamily == defaultFamily) {
      return fallback();
    }

    // Se a fonte ativa é uma fonte customizada importada pelo usuário (.ttf/.otf local)
    if (CustomFontLoader.loadedFontFamilies.contains(activeFamily)) {
      TextStyle s = textStyle ?? const TextStyle();
      return s.copyWith(
        fontFamily: activeFamily,
        color: color,
        backgroundColor: backgroundColor,
        fontSize: fontSize,
        fontWeight: fontWeight,
        fontStyle: fontStyle,
        letterSpacing: letterSpacing,
        wordSpacing: wordSpacing,
        textBaseline: textBaseline,
        height: height,
        locale: locale,
        foreground: foreground,
        background: background,
        shadows: shadows,
        fontFeatures: fontFeatures,
        decoration: decoration,
        decorationColor: decorationColor,
        decorationStyle: decorationStyle,
        decorationThickness: decorationThickness,
      );
    }

    // Caso contrário, carrega a fonte global escolhida via GoogleFonts dinâmico
    try {
      return gf.GoogleFonts.getFont(
        activeFamily,
        textStyle: textStyle,
        color: color,
        backgroundColor: backgroundColor,
        fontSize: fontSize,
        fontWeight: fontWeight,
        fontStyle: fontStyle,
        letterSpacing: letterSpacing,
        wordSpacing: wordSpacing,
        textBaseline: textBaseline,
        height: height,
        locale: locale,
        foreground: foreground,
        background: background,
        shadows: shadows,
        fontFeatures: fontFeatures,
        decoration: decoration,
        decorationColor: decorationColor,
        decorationStyle: decorationStyle,
        decorationThickness: decorationThickness,
      );
    } catch (_) {
      return fallback();
    }
  }

